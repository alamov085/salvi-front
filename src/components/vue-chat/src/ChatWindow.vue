<template>
  <div class="sc-chat-window" :class="{ opened: isOpen, closed: !isOpen }">
    <Header
      :title="title"
      :image-url="titleImageUrl"
      :on-close="onClose"
      :colors="colors"
      @userList="handleUserListToggle"
    />
    <UserList
      v-if="!currentChatUser"
      :participants="participants"
      :first-guest-message="firstGuestMessage"
      :validation-error="validationError"
    />
    <MessageList
      v-if="currentChatUser"
      :messages="messages"
      :participants="participants"
      :show-typing-indicator="showTypingIndicator"
      :colors="colors"
      :always-scroll-to-bottom="alwaysScrollToBottom"
      :message-styling="messageStyling"
      @scrollToTop="$emit('scrollToTop')"
    />
    <UserInput
      v-if="currentChatUser"
      :show-emoji="showEmoji"
      :on-submit="onUserInputSubmit"
      :suggestions="getSuggestions()"
      :show-file="showFile"
      :placeholder="placeholder"
      :colors="colors"
      @onType="$emit('onType')"
    />
  </div>
</template>

<script>
import Header from "./Header.vue"
import MessageList from "./MessageList.vue"
import UserInput from "./UserInput.vue"
import UserList from "./UserList.vue"
import { mapGetters } from "vuex"

export default {
  components: {
    Header,
    MessageList,
    UserInput,
    UserList
  },
  props: {
    showEmoji: {
      type: Boolean,
      default: false
    },
    showFile: {
      type: Boolean,
      default: false
    },
    participants: {
      type: Array,
      required: true
    },
    title: {
      type: String,
      required: true
    },
    titleImageUrl: {
      type: String,
      default: ""
    },
    onUserInputSubmit: {
      type: Function,
      required: true
    },
    onClose: {
      type: Function,
      required: true
    },
    messageList: {
      type: Array,
      default: () => []
    },
    isOpen: {
      type: Boolean,
      default: () => false
    },
    placeholder: {
      type: String,
      default: "Write a reply"
    },
    showTypingIndicator: {
      type: String,
      required: true
    },
    colors: {
      type: Object,
      required: true
    },
    alwaysScrollToBottom: {
      type: Boolean,
      required: true
    },
    messageStyling: {
      type: Boolean,
      required: true
    },
    firstGuestMessage: {
      type: Function,
      required: true
    },
    validationError: {
      type: Array,
      required: true
    }
  },
  data() {
    return {
      showUserList: false
    }
  },
  computed: {
    messages() {
      let messages = this.messageList
      return messages
    },
    ...mapGetters("chat", ["currentChatId", "currentChatUser"])
  },
  methods: {
    handleUserListToggle(showUserList) {
      this.showUserList = showUserList
    },
    getSuggestions() {
      return this.messages.length > 0
        ? this.messages[this.messages.length - 1].suggestions
        : []
    }
  }
}
</script>
